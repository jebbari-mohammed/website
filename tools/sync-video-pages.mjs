async function collectHtmlFiles(directory, relativeDirectory = '') {
  const entries = await readdir(directory, { withFileTypes: true })
  const files = []

  for (const entry of entries) {
    const relativePath = path.posix.join(relativeDirectory, entry.name)
    const absolutePath = path.join(directory, entry.name)
    if (entry.isDirectory()) {
      files.push(...(await collectHtmlFiles(absolutePath, relativePath)))
    } else if (entry.isFile() && entry.name.endsWith('.html')) {
      files.push({ absolutePath, relativePath })
    }
  }

  return files
}

function attribute(tag, name) {
  return tag.match(new RegExp(`\\b${name}\\s*=\\s*(["'])(.*?)\\1`, 'i'))?.[2]
}

function decodeEntities(value = '') {
  return value
    .replaceAll('&amp;', '&')
    .replaceAll('&quot;', '"')
    .replaceAll('&#39;', "'")
    .replaceAll('&#x27;', "'")
    .replaceAll('&lt;', '<')
    .replaceAll('&gt;', '>')
}

function htmlEscape(value = '') {
  return String(value)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#39;')
}

function xmlEscape(value = '') {
  return htmlEscape(value).replaceAll('&#39;', '&apos;')
}

function stripTags(value = '') {
  return decodeEntities(value.replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim())
}

function stripVideoSuffix(value = '') {
  return value
    .replace(/\s*(?:\||—|-)\s*IZEM(?: AI Fitness Coach)?\s*$/i, '')
    .replace(/\s+video\s+(?:guide|overview)\s*$/i, '')
    .trim()
}

function normalizedDate(value) {
  const match = String(value || '').match(/^\d{4}-\d{2}-\d{2}(?:T[^\s]+)?/)
  return match?.[0]
}

function googleVideoDateTime(value) {
  const date = normalizedDate(value)
  if (!date) return ''
  if (/^\d{4}-\d{2}-\d{2}$/.test(date)) return `${date}T00:00:00Z`
  if (/(?:Z|[+-]\d{2}:\d{2})$/i.test(date)) return date
  return `${date}Z`
}

function firstMatch(html, regex) {
  return decodeEntities(html.match(regex)?.[1]?.trim() || '')
}

function pageMetadata(html, relativePath) {
  const htmlTag = html.match(/<html\b[^>]*>/i)?.[0] || ''
  const canonicalTag = (html.match(/<link\b[^>]*>/gi) || []).find((tag) =>
    (attribute(tag, 'rel') || '').toLowerCase().split(/\s+/).includes('canonical'),
  )
  const canonical = canonicalTag ? attribute(canonicalTag, 'href') : ''
  const metaDescriptionTag = (html.match(/<meta\b[^>]*>/gi) || []).find(
    (tag) => (attribute(tag, 'name') || '').toLowerCase() === 'description',
  )
  const description = metaDescriptionTag ? attribute(metaDescriptionTag, 'content') || '' : ''
  const title = stripVideoSuffix(stripTags(firstMatch(html, /<title\b[^>]*>([\s\S]*?)<\/title>/i)))
  const date = normalizedDate(
    html.match(/"uploadDate"\s*:\s*"([^"]+)"/i)?.[1] ||
      html.match(/"datePublished"\s*:\s*"([^"]+)"/i)?.[1],
  )

  return {
    canonical: canonical ? new URL(canonical, siteOrigin).href : '',
    date,
    description: decodeEntities(description).trim(),
    language: attribute(htmlTag, 'lang') || '',
    relativePath,
    title,
  }
}

function sourcePriority(source) {
  if (/^blog\/[^/]+\.html$/.test(source.relativePath)) return 0
  if (source.language.toLowerCase().startsWith('en')) return 1
  return 2
}

