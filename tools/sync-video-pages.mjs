import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const publicDirectory = path.join(projectRoot, 'public')
const youtubeDirectory = path.join(publicDirectory, 'youtube')
const youtubeHubPath = path.join(youtubeDirectory, 'index.html')
const catalogPath = path.join(youtubeDirectory, 'video-catalog.json')
const videoSitemapPath = path.join(publicDirectory, 'video-sitemap.xml')
